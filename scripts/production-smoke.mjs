import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const temp=path.join(root,'.runtime','browser-tmp');fs.mkdirSync(temp,{recursive:true});
const executablePath=process.env.CAPY_CHROME??[
  path.join(process.env.PROGRAMFILES??'C:/Program Files','Google/Chrome/Application/chrome.exe'),
  path.join(process.env['PROGRAMFILES(X86)']??'C:/Program Files (x86)','Microsoft/Edge/Application/msedge.exe'),
].find(file=>fs.existsSync(file));
if(!executablePath)throw new Error('Set CAPY_CHROME to an installed Chrome/Edge executable.');
const browser=await chromium.launch({headless:true,executablePath,env:{...process.env,TEMP:temp,TMP:temp},args:['--disable-breakpad','--disable-crash-reporter']});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const click=action=>page.locator(`[data-action="${action}"]`).filter({visible:true}).first().click();
const stored=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('capybara_defense_v1:profile')));
try{
  await page.goto('http://127.0.0.1:4175/?dev=1',{waitUntil:'networkidle'});
  assert.equal(await page.evaluate(()=>typeof window.__CAPY_DEBUG__),'undefined');
  assert.match(await page.locator('.edition').innerText(),/v1\.0/);
  assert.equal(await page.locator('#dev-rank option').count(),54);
  assert.equal(await page.locator('#dev-boss option').count(),12);
  assert.equal(await page.locator('#dev-map option').count(),5);
  await page.locator('[data-action="start"]').click();
  await page.locator('[data-action="food"]').click();
  assert.equal(await page.locator('#food-value').innerText(),'540');
  await page.locator('[data-action="summon"]').click();
  assert.equal(await page.locator('#food-value').innerText(),'530');
  assert.equal(await page.locator('#summon-title').innerText(),'换一窝');
  assert.match(await page.locator('#summon-note').innerText(),/5/);
  await page.locator('[data-action="summon"]').click();
  assert.equal(await page.locator('#food-value').innerText(),'520');
  await page.locator('[data-action="pause"]').click();
  assert.ok(await page.locator('#game-dialog').evaluate(e=>e.open));
  await page.locator('[data-action="surrender"]').click();
  await page.locator('#game-dialog [data-action="menu"]').click();
  await page.reload({waitUntil:'networkidle'});
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('capybara_defense_v1:profile')));
  assert.equal(saved.matches,1);assert.equal(saved.wins,0);assert.equal(saved.fragments.length,0);
  await click('test-enable');
  const full=await stored();
  assert.equal(full.coins,9999);assert.equal(full.unlockedWeapons.length,36);
  assert.equal(Object.keys(full.equippedWeapons).length,12);assert.equal(Object.keys(full.ownedProps).length,20);
  assert.equal(full.stars,180);assert.equal(full.unlockedAvatars.length,16);assert.equal(full.mergedHeroes.length,12);
  assert.equal(await page.locator('#menu-map option').count(),5);
  await click('profile');assert.equal(await page.locator('.avatar-card').count(),16);await click('close-profile');
  await click('leaderboard');assert.equal(await page.locator('.leaderboard-row').count(),16);
  assert.equal(await page.locator('.leaderboard-row').first().getAttribute('data-player'),'true');await click('close-profile');
  await click('settings');
  await page.locator('[data-setting="musicVolume"]').evaluate(element=>{element.value='0.25';element.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.locator('[data-setting="showDamageNumbers"]').uncheck();
  assert.equal((await stored()).settings.musicVolume,.25);assert.equal((await stored()).settings.showDamageNumbers,false);
  await click('close-profile');
  await click('armory');assert.equal(await page.locator('.weapon-card').count(),36);
  await page.locator('[data-weapon="m01_swatter"]').selectOption('kungfu_po');
  assert.equal((await stored()).equippedWeapons.kungfu_po,'m01_swatter');
  await page.locator('#game-dialog [data-action="en"]').click();
  assert.match(await page.locator('.weapon-card').first().innerText(),/Fly Swatter/);
  await click('close-meta');await click('zh-CN');
  await page.evaluate(()=>{window.__productionOriginalRandom=Math.random;Math.random=()=>.375;});
  await click('market');await click('meta-tab:lottery');
  assert.equal(await page.locator('.lottery-cell').count(),8);
  await click('meta-spin');
  assert.equal((await stored()).coins,9959); // 80 fee, 40 coin prize.
  const spun=await stored();
  await page.locator('#game-dialog [data-action="en"]').click();
  await page.locator('.lottery-result').waitFor();assert.deepEqual(await stored(),spun);
  await click('close-meta');await click('zh-CN');
  await page.evaluate(()=>{Math.random=window.__productionOriginalRandom;});
  await page.locator('[data-prop-slot="active:0"]').selectOption('catnip');
  await page.locator('[data-prop-slot="active:1"]').selectOption('glue_trap');
  await page.locator('#menu-map').selectOption('cat_tower_maze');
  assert.equal((await stored()).selectedMap,'cat_tower_maze');
  await click('start');
  assert.match(await page.locator('#battle-hud .map-eyebrow').innerText(),/猫爬架迷宫/);
  assert.equal(await page.locator('.battle-prop').count(),2);assert.equal(await page.locator('.passive-icons > span').count(),6);
  await click('prop:catnip');assert.ok(await page.locator('[data-action="prop:catnip"]').isDisabled());
  await click('sprinkler');assert.ok(await page.locator('[data-action="sprinkler"]').isDisabled());
  await page.screenshot({path:path.join(root,'verification','production-m3-battle.png'),fullPage:true});
  await click('pause');await click('surrender');await click('menu');await click('test-restore');
  assert.deepEqual(await stored(),saved);
  assert.equal(await page.evaluate(()=>localStorage.getItem('capybara_defense_v1:normalProfileBackup')),null);
  await page.reload({waitUntil:'networkidle'});assert.deepEqual(await stored(),saved);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(root,'verification','production-smoke.json'),JSON.stringify({passed:true,errors,checks:['Built v1.0 bundle loads without debug API; 54 ranks, 12 bosses and four debug maps available','Actual five-card summon and redraw controls work','Pause and surrender persist once','Full M3 profile includes 180 stars, 16 avatars, 12 merged heroes and all four maps','Avatar gallery, 16-row leaderboard and immediate settings persistence work','Full test profile, 36-weapon armory and bilingual equipment work','Paid lottery deducts 80 and rewards 40 exactly once across language change','Selected Cat Tower map persists and appears in actual battle','Battle renders 2+6 equipment; actual catnip and sprinkler enter cooldown/used state','Restoring normal profile discards test changes and survives reload']},null,2));
  console.log('PASS production M1/M2 regression and M3 rank/avatar/leaderboard/settings/map controls, normal save restoration, zero console errors');
}finally{await browser.close();}
